    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
    
    try {

        Connection con = DriverManager.getConnection(
            "jdbc:mysql://localhost:3306/fondatel",
            "root",
            ""
        );

        String sql = "INSERT INTO alimentos "
                + "(idalimentos, nombre, descripcion, precio, foto, categoria, estado) "
                + "VALUES (?, ?, ?, ?, ?, ?, ?)";

        PreparedStatement ps = con.prepareStatement(sql);

        // Obtener los datos del formulario
 ps.setInt(1, Integer.parseInt(idalimento.getText()));
        ps.setString(2, txnombre.getText());
        ps.setString(3, txdescripcion.getText());
        ps.setDouble(4, Double.parseDouble(txprecio.getText()));
        ps.setString(5, txfoto.getText());
        ps.setString(6, cbcategoria.getSelectedItem().toString());
        ps.setString(7, cbestado.getSelectedItem().toString());

        // Registrar alimento
        ps.executeUpdate();

        JOptionPane.showMessageDialog(this,
                "Alimento registrado correctamente");

        // Cerrar conexión
        ps.close();
        con.close();

        // Actualizar JTable
        cnx.entablar("SELECT * FROM alimentos", TAlimentos);

        // Limpiar campos
        idalimento.setText("");
        txnombre.setText("");
        txdescripcion.setText("");
        txprecio.setText("");
        txfoto.setText("");

    } catch (NumberFormatException e) {

        JOptionPane.showMessageDialog(this,
                "El ID y el precio deben ser números");

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(this,
                "Error al registrar: " + e.getMessage());

    }


    }//GEN-LAST:event_jButton1ActionPerformed

